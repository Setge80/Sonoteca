-- Ejecutar conectado A LA BASE DE DATOS sonoteca:
-- psql -h localhost -U sonoteca -d sonoteca -f sonoteca.sql
-- ---------------------------------------------------------------------------
DROP TABLE IF EXISTS lista_cancion;
DROP TABLE IF EXISTS listas_reproduccion;
DROP TABLE IF EXISTS canciones;
DROP TABLE IF EXISTS albumes;
DROP TABLE IF EXISTS artistas;
DROP TABLE IF EXISTS generos;
CREATE TABLE generos (
                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nombre VARCHAR(50) NOT NULL UNIQUE
);
CREATE TABLE artistas (
                          id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          nombre VARCHAR(100) NOT NULL,
                          nacionalidad VARCHAR(50)
);
CREATE TABLE albumes (
                         id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         titulo VARCHAR(150) NOT NULL,
                         anio INTEGER,
                         artista_id INTEGER NOT NULL,
                         genero_id INTEGER NOT NULL,
                         CONSTRAINT fk_album_artista FOREIGN KEY (artista_id) REFERENCES artistas(id),
                         CONSTRAINT fk_album_genero FOREIGN KEY (genero_id) REFERENCES generos(id)
);
CREATE TABLE canciones (
                           id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           titulo VARCHAR(150) NOT NULL,
                           duracion_segundos INTEGER NOT NULL,
                           numero_pista INTEGER,
                           album_id INTEGER NOT NULL,
                           CONSTRAINT fk_cancion_album FOREIGN KEY (album_id) REFERENCES albumes(id)
);
-- Las dos siguientes no se usan hasta la unidad 4 (Hibernate), pero se crean
-- ahora para tener el esquema completo desde el principio.
CREATE TABLE listas_reproduccion (
                                     id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     nombre VARCHAR(100) NOT NULL
);
CREATE TABLE lista_cancion (
                               lista_id INTEGER NOT NULL,
                               cancion_id INTEGER NOT NULL,
                               posicion INTEGER NOT NULL,
                               PRIMARY KEY (lista_id, cancion_id),
                               CONSTRAINT fk_lc_lista FOREIGN KEY (lista_id) REFERENCES listas_reproduccion(id),
                               CONSTRAINT fk_lc_cancion FOREIGN KEY (cancion_id) REFERENCES canciones(id)
);
CREATE INDEX idx_albumes_artista ON albumes(artista_id);
CREATE INDEX idx_canciones_album ON canciones(album_id);
CREATE INDEX idx_canciones_titulo ON canciones(titulo);
